
/* =========================================
   IRANGARD - SERVICE WORKER
   Offline PWA Support
   ========================================= */

"use strict";

const CACHE_NAME = "irangard-cache-v2";

const APP_SHELL = [
    "./",
    "./index.html",
    "./manifest.json",
    "./css/styles.css",
    "./js/app.js",
    "./locales/fa.json",
    "./locales/en.json"
];

/* =========================================
   INSTALL
   ========================================= */

self.addEventListener("install", event => {

    event.waitUntil(

        caches.open(CACHE_NAME).then(cache => {
            return cache.addAll(APP_SHELL);
        })

    );

    self.skipWaiting();
});

/* =========================================
   ACTIVATE
   ========================================= */

self.addEventListener("activate", event => {

    event.waitUntil(

        caches.keys().then(cacheNames => {

            return Promise.all(

                cacheNames.map(cacheName => {

                    if (cacheName !== CACHE_NAME) {
                        return caches.delete(cacheName);
                    }

                })

            );

        })

    );

    self.clients.claim();
});

/* =========================================
   FETCH STRATEGIES
   ========================================= */

self.addEventListener("fetch", event => {

    const request = event.request;

    // Only handle GET requests.
    if (request.method !== "GET") {
        return;
    }

    const url = new URL(request.url);

    // Do not intercept external requests.
    if (url.origin !== self.location.origin) {
        return;
    }

    // Locale files: network first, cached fallback.
    if (url.pathname.includes("/locales/")) {

        event.respondWith(

            fetch(request)
                .then(response => {

                    if (response.ok) {

                        const copy = response.clone();

                        caches.open(CACHE_NAME).then(cache => {
                            cache.put(request, copy);
                        });

                    }

                    return response;

                })
                .catch(async () => {

                    const cached = await caches.match(request);

                    if (cached) {
                        return cached;
                    }

                    return new Response(
                        JSON.stringify({
                            error: "Offline language unavailable"
                        }),
                        {
                            status: 503,
                            headers: {
                                "Content-Type": "application/json"
                            }
                        }
                    );

                })

        );

        return;
    }

    // Navigation requests: network first, app shell fallback.
    if (request.mode === "navigate") {

        event.respondWith(

            fetch(request)
                .catch(async () => {

                    return await caches.match("./index.html")
                        || new Response(
                            "Irangard is currently offline.",
                            {
                                status: 503,
                                headers: {
                                    "Content-Type": "text/plain"
                                }
                            }
                        );

                })

        );

        return;
    }

    // Static assets: cache first.
    event.respondWith(

        caches.match(request).then(cachedResponse => {

            if (cachedResponse) {
                return cachedResponse;
            }

            return fetch(request).then(response => {

                if (
                    response &&
                    response.status === 200 &&
                    response.type === "basic"
                ) {

                    const copy = response.clone();

                    caches.open(CACHE_NAME).then(cache => {
                        cache.put(request, copy);
                    });

                }

                return response;

            });

        })

    );

});
